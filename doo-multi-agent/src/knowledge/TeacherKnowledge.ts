/** 根据评估弱项维度选择叙事火车活动案例 */
export function getTrainCaseForAssessment(assessment: {
  dimensions: {
    diction: { vocabulary: number; sentenceStructure: number };
    organization: {
      narrativeStructure: number;
      themeRelevance: number;
      eventExpansion: number;
      expressiveness: number;
    };
    opinion: { narrativeViewpoint: number };
  };
}): TrainActivityCase {
  const d = assessment.dimensions;
  if (d.opinion.narrativeViewpoint <= 1) {
    return NARRATIVE_TRAIN_CASES.find(c => c.key === 'talking_peach')!;
  }
  if (d.diction.vocabulary <= 1 || d.diction.sentenceStructure <= 1) {
    return NARRATIVE_TRAIN_CASES.find(c => c.key === 'flying_kindergarten')!;
  }
  return NARRATIVE_TRAIN_CASES.find(c => c.key === 'forest_courier')!;
}

/** 格式化叙事火车活动案例（教师主持人格式） */
export function formatTrainCase(activityCase: TrainActivityCase): string {
  const lines: string[] = [];
  lines.push(`📌 ${activityCase.name}`);
  lines.push('');
  lines.push(`【活动定位】${activityCase.positioning}`);
  lines.push('');
  lines.push(`【核心维度】${activityCase.dimension}（DOO · ${activityCase.coreDimension === 'diction' ? '词句D' : activityCase.coreDimension === 'organization' ? '组织O' : '观点O'}）`);
  lines.push('');
  lines.push('【叙事目标】');
  activityCase.objectives.forEach(o => lines.push(`  • ${o}`));
  lines.push('');
  lines.push('【前期准备】');
  activityCase.prepare.forEach(p => lines.push(`  • ${p}`));
  lines.push('');
  lines.push('【活动过程】');
  activityCase.process.forEach(p => lines.push(`  • ${p}`));
  lines.push('');
  lines.push('【教师支架策略】');
  activityCase.scaffolds.forEach(s => lines.push(`  • ${s}`));
  lines.push('');
  lines.push('【观察要点】');
  activityCase.observations.forEach(o => lines.push(`  • ${o}`));
  lines.push('');
  lines.push('【智能体协同】');
  activityCase.collaboration.forEach(c => lines.push(`  • ${c}`));
  lines.push('');
  lines.push(`【评估摘要】${activityCase.evaluationSummary}`);
  return lines.join('\n');
}
