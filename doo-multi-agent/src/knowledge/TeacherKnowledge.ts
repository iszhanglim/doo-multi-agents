/** 根据活动类型查找可参考的活动 */
export function findActivitiesByType(type: keyof typeof ACTIVITY_LIBRARY): string {
  const lib = ACTIVITY_LIBRARY[type];
  if (!lib) return '';
  const lines: string[] = [];
  lines.push(`${lib.name}：${lib.desc}`);
  lib.activities.forEach(a => {
    lines.push('');
    lines.push(`  📖 ${a.name}`);
    lines.push(`    目标：${a.aim}`);
    lines.push(`    提问示例：${a.questions[0]} ${a.questions[1] || ''}`);
    lines.push(`    亮点：${a.highlight}`);
  });
  return lines.join('\n');
}

