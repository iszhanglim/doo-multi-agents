/** 根据弱项维度选择活动案例 */
/** 根据弱项维度选择活动案例 */
export function getActivityCaseForAssessment(assessment: {
  dimensions: {
    diction: { vocabulary: number; sentenceStructure: number };
    organization: {
      narrativeStructure: number;
      themeRelevance: number;
      eventExpansion: number;
      expressiveness: number;
    };
    opinion: { narrativeViewpoint: number };
  };
}): typeof ACTIVITY_CASES.diction {
  const d = assessment.dimensions;
  // 5分制：1-3分为初级需支持，据此选择活动案例
  // 词句弱 → 用谜语或小超市；组织弱 → 用故事小火车/画面接龙；表现弱 → 用故事小剧场；观点弱 → 用评论员
  if (d.diction.vocabulary <= 3 || d.diction.sentenceStructure <= 3) {
    return d.diction.vocabulary <= 3 ? ACTIVITY_CASES.guessing : ACTIVITY_CASES.diction;
  }
  if (d.organization.narrativeStructure <= 3 || d.organization.themeRelevance <= 3) {
    return ACTIVITY_CASES.organization;
  }
  if (d.organization.eventExpansion <= 3 || d.organization.expressiveness <= 3) {
    return ACTIVITY_CASES.dialogue;
  }
  if (d.organization.narrativeStructure <= 3 && d.organization.themeRelevance <= 3) {
    return ACTIVITY_CASES.pictureTalk;
  }
  if (d.opinion.narrativeViewpoint <= 3) {
    return ACTIVITY_CASES.opinion;
  }
  return ACTIVITY_CASES.overall;
}

/** 格式化活动案例为多行文本 */
export function formatActivityCase(activityCase: typeof ACTIVITY_CASES.diction): string {
  const lines: string[] = [];
  lines.push(`📌 ${activityCase.name}`);
  lines.push('');
  lines.push(`【设计意图】${activityCase.design}`);
  lines.push('');
  lines.push('【活动目标】');
  activityCase.objectives.forEach(o => lines.push(`  • ${o}`));
  lines.push('');
  lines.push('【活动准备】');
  activityCase.prepare.forEach(p => lines.push(`  • ${p}`));
  lines.push('');
  lines.push('【活动过程】');
  activityCase.process.forEach(p => lines.push(`  • ${p}`));
  lines.push('');
  lines.push(`【活动评析】${activityCase.evaluation}`);
  return lines.join('\n');
}

